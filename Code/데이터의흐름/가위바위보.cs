using System;

class Program
{
    static void Main()
    {
        // 점수판 초기화
        int 나_점수 = 0;
        int 남_점수 = 0;

        // 내가 가위 입력
        Console.Write("나 (가위, 바위, 보 중 입력): ");
        string 나 = Console.ReadLine();

        // 상대(남)의 값 랜덤 생성
        string[] 선택지 = { "가위", "바위", "보" };
        Random rand = new Random();
        string 남 = 선택지[rand.Next(0, 3)]; // 0, 1, 2 중 무작위 인덱스 선택

        // 상대가 무엇을 냈는지 확인하기 위한 출력
        Console.WriteLine($"상대(남)의 선택: {남}");

        // 3x3 조건문 (9가지 경우의 수)
        // 1. 내가 가위일 때 (상대: 가위, 바위, 보)
        if (나 == "가위" && 남 == "가위")
        {
            // 무승부 (점수 변동 없음)
        }
        else if (나 == "가위" && 남 == "바위")
        {
            남_점수 += 1;
        }
        else if (나 == "가위" && 남 == "보")
        {
            나_점수 += 1;
        }
        // 2. 내가 바위일 때 (상대: 가위, 바위, 보)
        else if (나 == "바위" && 남 == "가위")
        {
            나_점수 += 1;
        }
        else if (나 == "바위" && 남 == "바위")
        {
            // 무승부
        }
        else if (나 == "바위" && 남 == "보")
        {
            남_점수 += 1;
        }
        // 3. 내가 보일 때 (상대: 가위, 바위, 보)
        else if (나 == "보" && 남 == "가위")
        {
            남_점수 += 1;
        }
        else if (나 == "보" && 남 == "바위")
        {
            나_점수 += 1;
        }
        else if (나 == "보" && 남 == "보")
        {
            // 무승부
        }

        // 점수판 출력
        Console.WriteLine($"[점수판] 나 : {나_점수}점 | 남 : {남_점수}점");
    }
}
